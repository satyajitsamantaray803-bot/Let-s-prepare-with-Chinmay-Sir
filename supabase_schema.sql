create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  description text,
  created_at timestamptz default now()
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  course_code text,
  resource_type text default 'PDF',
  url text not null,
  created_at timestamptz default now()
);

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  meeting_url text,
  video_url text,
  scheduled_at timestamptz,
  created_at timestamptz default now()
);

-- Enable Row Level Security.
alter table public.courses enable row level security;
alter table public.resources enable row level security;
alter table public.classes enable row level security;

-- Safe public read-only access for the student website.
drop policy if exists "Public can read courses" on public.courses;
create policy "Public can read courses"
on public.courses for select
to anon, authenticated
using (true);

drop policy if exists "Public can read resources" on public.resources;
create policy "Public can read resources"
on public.resources for select
to anon, authenticated
using (true);

drop policy if exists "Public can read classes" on public.classes;
create policy "Public can read classes"
on public.classes for select
to anon, authenticated
using (true);

grant select on public.courses, public.resources, public.classes to anon, authenticated;

-- IMPORTANT:
-- No public INSERT/UPDATE/DELETE policies are created.
